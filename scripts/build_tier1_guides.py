ASKED = [
    ("Гоблинские дела", "где найти ящик"),
    ("Шпиономания", "цепочка и награда"),
    ("Затерянный объект", "где искать"),
    ("Железная гора", "прохождение"),
    ("Взлом ПДА Бороды", "болота, где лежит и как вскрыть"),
    ("Взлом ПДА Мёртвой породы", "как пройти взлом"),
    ("Как расколоть Цитуса", "за Зарю"),
    ("Встретиться со свидетелем распада", "куда идти"),
    ("Квест Варяга", "шаги и что даёт"),
    ("Глаз", "прохождение"),
]


def build_kvesty():
    q = g("/api/quests")
    factions = [f["name"] for f in q.get("factions") or []]
    pub = [i for i in q.get("items") or [] if i.get("published")]

    asked = "\n".join(
        f'<h3>{n}</h3>\n<!-- ЗАПОЛНИТЬ: шаги, где начинается, награда. '
        f'Поисковый интент: «{hint}» -->\n<p>—</p>' for n, hint in ASKED)
    fac = "\n".join(f'  <li><b>{f}</b> — <!-- ЗАПОЛНИТЬ: за что берут линейку, '
                    f'что даёт --></li>' for f in factions)
    have = "\n".join(f'  <li><a href="/quests/{i["id"]}">{i["title"]}</a></li>'
                     for i in pub[:20])

    html = f"""
<!-- ЧЕРНОВИК. Каркас собран скриптом build_tier1_guides.py по реальным
     поисковым запросам. Прохождения дописать руками: цифры и шаги квестов в
     базе сайта не хранятся, генерировать их нельзя. -->
<p>Квесты в STALZONE — это не только сюжет: линейки дают снаряжение, запчасти и
доступ к торговцам. Блок-схемы линеек с зависимостями и точками на карте — в
разделе <a href="/quests">квесты</a>; ниже — разбор тех заданий, на которых чаще
всего застревают.</p>

<h2>Как устроены линейки</h2>
<ul>
{fac}
</ul>
<!-- ЗАПОЛНИТЬ: чем отличаются сюжетные (main) от побочных, что переносится
     между группировками, можно ли брать линейки параллельно -->

<h2>Что уже разобрано по шагам</h2>
<ul>
{have or "  <li>—</li>"}
</ul>
<p>Отдельным гайдом разобрано <a href="/guides/eho-proshlogo">«Эхо прошлого»</a>
и <a href="/guides/konvert-s-baksami">конверт с баксами</a>.</p>

<h2>Частые вопросы по конкретным квестам</h2>
{asked}

<h2>Награды: что из этого стоит времени</h2>
<!-- ЗАПОЛНИТЬ: таблица «квест → награда → сколько стоит награда на ауке».
     Цены можно подтянуть скриптом, когда награды будут заведены в quests.db -->
<p>—</p>

<blockquote><p><b>Коротко.</b> Линейки квестов — самый дешёвый источник
снаряжения на старте. Схемы зависимостей и точки на карте — в разделе
<a href="/quests">квесты</a>.</p></blockquote>
"""
    write("kvesty-stalzone", {
        "slug": "kvesty-stalzone",
        "title": "Квесты в STALZONE: линейки группировок, прохождения и награды",
        "description": ("Квесты STALZONE (Сталкрафт): линейки шести группировок, "
                        "прохождение сложных заданий по шагам и что дают награды."),
        "created_at": TODAY, "updated_at": TODAY, "cover": "",
        "tags": ["Квесты", "Прохождение"],
        "published": 0,
    }, html)


