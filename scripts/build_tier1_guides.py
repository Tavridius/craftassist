def _best_offer(d, prev_id):
    """Самый дешёвый обмен предмета: считаем сами, а не берём cost из API.

    cost/cost_partial включает закупку трейд-ина на ауке — при проходе ветки
    целиком предыдущая ступень уже куплена шагом раньше, иначе она посчиталась
    бы дважды (у РШ-12 это лишние 8.9 млн за Colt Python).
    """
    best = None
    for w in d.get("ways") or []:
        for o in w.get("offers") or []:
            buy, farm = 0, []
            for i in o.get("inputs") or []:
                if prev_id and i["id"] == prev_id:
                    continue                      # трейд-ин — предыдущая ступень
                if i.get("line_cost"):
                    buy += i["line_cost"]
                else:
                    farm.append((i["name"], i["amount"]))
            money = o.get("money") or 0 if o.get("currency") == "money" else 0
            total = buy + money
            if best is None or total < best["total"]:
                best = {"total": total, "buy": buy, "money": money, "farm": farm,
                        "where": w["settlement_name"], "level": w["level"]}
    return best


