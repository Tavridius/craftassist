def short(name):
    """«Бронекостюм «Центурион»» → «Центурион»: в заголовок не влезают кавычки
    внутри кавычек, а игровые имена почти всегда содержат ёлочки."""
    if "«" in name and "»" in name:
        return name[name.rindex("«") + 1:name.rindex("»")]
    return name


