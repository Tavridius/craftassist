#!/usr/bin/env python3
"""Сборка гайдов на живых данных прода в backend/content/guides/.

Зачем скрипт, а не руками: тело этих гайдов — таблицы с реальными ценами
аукциона. Цифры устают, но аргумент гайда («на что смотреть») — нет. Когда
цифры устареют, гайд перегенерируется одной командой:

    python scripts/build_guides.py            # все
    python scripts/build_guides.py kraft      # только один

Пишет пары <slug>.html + <slug>.json. Бандл сидится в guides.db
insert-if-absent (см. db/guides.py), поэтому ПРАВКИ АДМИНА В UI НЕ
ПЕРЕТИРАЮТСЯ — чтобы обновить уже опубликованный гайд, нужно либо удалить его
в /dev/guides, либо вставить новое тело туда же руками.

Иконки предметов берём с прода (/icons/...) — они уже раздаются nginx'ом, это
законный источник картинок для таблиц.
"""
import json
import os
import statistics
import sys
import urllib.request
from datetime import date

if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")

BASE = "https://stalzone-helper.ru"
OUT = os.path.join(os.path.dirname(os.path.dirname(os.path.abspath(__file__))),
                   "backend", "content", "guides")
JUNK = 9_999_999_999          # заглушка «нет предложений» в min_buyout
MIN_N = 20                    # минимум продаж в корзине за 7 дней
TODAY = date.today().isoformat()
# Системный SOCKS-прокси на машине ломает http-клиенты — ходим напрямую.
_o = urllib.request.build_opener(urllib.request.ProxyHandler({}))


def g(path):
    with _o.open(BASE + path, timeout=120) as r:
        return json.load(r)


def rub(n):
    return f"{int(round(n)):,}".replace(",", " ")     # неразрывный пробел


def name_cell(r):
    return (f'<div class="gn"><img class="gi" src="/{r["icon"]}" alt="{r["name"]}"'
            f' loading="lazy" width="32" height="32">'
            f'<a href="/item/{r["id"]}">{r["name"]}</a></div>')


def table(head, rows):
    th = "".join(f"<th>{h}</th>" for h in head)
    body = "\n".join("    <tr>" + "".join(f"<td>{c}</td>" for c in r) + "</tr>"
                     for r in rows)
    return ('<div class="gt-wrap">\n  <table class="gt">\n'
            f'    <thead><tr>{th}</tr></thead>\n    <tbody>\n{body}\n'
            '    </tbody>\n  </table>\n</div>')


def snap(extra=""):
    return (f'<p class="gsnap">Снимок цен: {TODAY}. '
            f'Живые цифры всегда в калькуляторе{extra}.</p>')


def write(slug, meta, html):
    os.makedirs(OUT, exist_ok=True)
    with open(os.path.join(OUT, f"{slug}.json"), "w", encoding="utf-8") as f:
        json.dump(meta, f, ensure_ascii=False, indent=2)
        f.write("\n")
    with open(os.path.join(OUT, f"{slug}.html"), "w", encoding="utf-8") as f:
        f.write(html.strip() + "\n")
    print(f"  {slug}.html  ({len(html)} символов)")


# =======================  1. выгодный крафт  =======================
def build_kraft():
    d = g("/api/top")
    ok = [r for r in d["profitable"]
          if r.get("craft_cost") and r.get("sell_price")
          and 0 < r["sell_price"] < JUNK
          and (r.get("sales_per_hour") or 0) >= 1 and 0 < r["pct"] < 1500]
    ok.sort(key=lambda r: r["diff"], reverse=True)
    big = table(
        ["предмет", "крафт", "продажа", "чистыми", "выгода", "спрос"],
        [[name_cell(r), rub(r["craft_cost"]), rub(r["sell_price"]),
          f'<b>+{rub(r["diff"])}</b>', f'+{r["pct"]}%',
          f'{r["sales_per_hour"]:.0f}/ч'] for r in ok[:12]])

    small = sorted((r for r in ok if r["craft_cost"] < 10_000),
                   key=lambda r: r["pct"], reverse=True)[:8]
    cheap = table(
        ["предмет", "крафт", "продажа", "отдача", "спрос"],
        [[name_cell(r), rub(r["craft_cost"]), rub(r["sell_price"]),
          f'<b>+{r["pct"]}%</b>', f'{r["sales_per_hour"]:.0f}/ч'] for r in small])

    loss = [r for r in d["popular"] if (r.get("pct") is not None and r["pct"] < 0
                                        and r.get("craft_cost"))][:6]
    bad = table(
        ["предмет", "крафт", "продажа", "итог", "выгода"],
        [[name_cell(r), rub(r["craft_cost"]), rub(r["sell_price"]),
          f'<b class="bad">{rub(r["diff"])}</b>', f'{r["pct"]}%'] for r in loss])

    html = f"""
<p>Вопрос «что выгодно крафтить» обычно получает ответ «смотри аукцион и ищи разницу
20–30%». Ниже — уже посчитанная разница по <b>живым ценам аукциона</b>: во что
обходится крафт, за сколько предмет уходит и как часто его вообще берут.</p>

<h2>Самая большая выгода в рублях с одной штуки</h2>
<p>«Чистыми» — это цена продажи минус комиссия аукциона 5% и минус стоимость
ингредиентов. «Спрос» — сколько штук уходит на аукционе в час: без него большая
выгода бесполезна, продавать будет некому.</p>
{big}
{snap(' — <a href="/craft">калькулятор крафта</a>')}

<h2>Мелочь с максимальной отдачей</h2>
<p>Здесь выгода в процентах, а не в рублях: вход дешёвый, но и с одной штуки
немного. Годится, когда рублей на старте мало, а времени — много.</p>
{cheap}

<h2>А это крафтить не надо</h2>
<p>Обратная сторона, которую в гайдах обычно не пишут: часть популярных позиций
дешевле <b>купить готовыми</b>, чем собирать. Ингредиенты стоят дороже результата.</p>
{bad}

<h2>Как этим пользоваться</h2>
<ul>
  <li><b>Смотрите спрос, а не только процент.</b> +700% на предмете, который берут
    раз в сутки, — это не заработок.</li>
  <li><b>Комиссия 5% уже вычтена</b> в колонке «чистыми», отдельно считать не нужно.</li>
  <li><b>Еда и медикаменты</b> держатся в топе стабильнее железа: спрос ежедневный,
    цена почти не проседает.</li>
  <li><b>Проверяйте свои перки и станки.</b> Рецепт может требовать уровня убежища,
    которого у вас ещё нет — в <a href="/craft">калькуляторе</a> это видно сразу,
    а с профилем он подставит ваши уровни.</li>
</ul>

<blockquote><p><b>Коротко.</b> Выгодный крафт — это не «секретный рецепт», а
пересечение трёх колонок: дешёвый вход, живой спрос и разница больше комиссии.
Список выше пересобирается по текущему аукциону — а
<a href="/craft">калькулятор крафта</a> считает то же самое для любого предмета,
с учётом вашего убежища.</p></blockquote>
"""
    write("vygodnyy-kraft", {
        "slug": "vygodnyy-kraft",
        "title": "Что выгодно крафтить в STALZONE: расчёт по живым ценам аукциона",
        "description": ("Что выгодно крафтить в STALZONE (Сталкрафт) — таблица по живым "
                        "ценам аукциона: стоимость крафта, цена продажи, чистая выгода "
                        "за вычетом комиссии и спрос в час. Плюс позиции, которые "
                        "дешевле купить готовыми, чем крафтить."),
        "created_at": TODAY, "updated_at": TODAY,
        "cover": f"/{ok[0]['icon']}" if ok else "",
        "tags": ["Крафт", "Экономика", "Аукцион"],
    }, html)


