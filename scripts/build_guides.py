def build_zatochka():
    ids = set()
    for w in ("7d", "24h"):
        d = g(f"/api/artmarket/top?window={w}")
        for k in ("up", "down"):
            for r in d.get(k, []):
                ids.add(r["id"])
    pairs = []
    for iid in sorted(ids):
        try:
            d = g(f"/api/artmarket/{iid}")
        except Exception:
            continue
        by = {(b["qlt"], b["ptn"]): (b["avg7d"], b["n7"]) for b in d["buckets"]
              if b.get("avg7d") and (b.get("n7") or 0) >= MIN_N}
        for (qlt, ptn), (price, n) in sorted(by.items()):
            base = by.get((qlt, 0))
            if ptn and base:
                pairs.append({"item": d["item"], "qlt": qlt, "ptn": ptn,
                              "p0": base[0], "n0": base[1], "p": price, "n": n,
                              "pct": (price / base[0] - 1) * 100})
    med = {p: statistics.median([r["pct"] for r in pairs if r["ptn"] == p])
           for p in (5, 10, 15) if any(r["ptn"] == p for r in pairs)}
    cnt = {p: sum(1 for r in pairs if r["ptn"] == p) for p in (5, 10, 15)}

    ladder = table(
        ["заточка", "медианная надбавка", "во столько раз дороже", "пар в выборке"],
        [[f"<b>+{p}</b>", f"<b>{med[p]:+.0f}%</b>", f"×{1 + med[p] / 100:.1f}",
          str(cnt[p])] for p in sorted(med)])

    # Главное: надбавка ЗАВИСИТ от цены базового артефакта, и очень сильно.
    # Без этого разреза медиана вводит в заблуждение — в таблице примеров у
    # дорогих артефактов надбавка +20..70%, и читатель решит, что мы врём.
    b15 = [r for r in pairs if r["ptn"] == 15]
    brackets = [(0, 200_000, "дешевле 200 тыс."),
                (200_000, 1_000_000, "от 200 тыс. до 1 млн"),
                (1_000_000, 10 ** 15, "дороже 1 млн")]
    by_price = []
    for lo, hi, label in brackets:
        v = [r["pct"] for r in b15 if lo <= r["p0"] < hi]
        if v:
            m = statistics.median(v)
            by_price.append([label, f"<b>{m:+.0f}%</b>",
                             f"<b>×{1 + m / 100:.1f}</b>", str(len(v))])
    t_price = table(["цена базового артефакта", "медианная надбавка за +15",
                     "во столько раз дороже", "пар"], by_price)

    by_q = []
    for q in sorted({r["qlt"] for r in b15}):
        v = [r["pct"] for r in b15 if r["qlt"] == q]
        if len(v) >= 5:                    # выборки меньше 5 не показываем
            m = statistics.median(v)
            by_q.append([f"<b>{q}</b>", f"{m:+.0f}%", f"<b>×{1 + m / 100:.1f}</b>",
                         str(len(v))])
    t_qlt = table(["качество", "медианная надбавка за +15", "во столько раз дороже",
                   "пар"], by_q)

    pairs.sort(key=lambda r: -r["p"])
    top = table(
        ["артефакт", "качество", "заточка", "цена +0", "цена заточенного", "надбавка"],
        [[name_cell(r["item"]), str(r["qlt"]), f'+{r["ptn"]}',
          rub(r["p0"]), f'<b>{rub(r["p"])}</b>', f'{r["pct"]:+.0f}%']
         for r in pairs[:12]])
    cheap15 = min((r for r in b15 if r["p0"] < 200_000),
                  key=lambda r: r["p0"], default=None)

    m_low = statistics.median([r["pct"] for r in b15 if r["p0"] < 200_000])
    m_high = statistics.median([r["pct"] for r in b15 if r["p0"] >= 1_000_000])
    html = f"""
<p>«Стоит ли точить до +15» — вопрос, на который обычно отвечают «если ты в клане,
то неизбежно». Его можно посчитать: у нас есть история продаж аукциона
<b>по корзинам качества и заточки</b>, то есть видно, сколько люди реально платят
за заточенный артефакт против такого же незаточенного.</p>
<p>Главный вывод сразу: <b>универсального ответа нет</b>, надбавка за заточку
зависит от того, сколько стоит сам артефакт — и разница между дешёвыми и дорогими
почти десятикратная.</p>

<h2>Надбавка зависит от цены артефакта</h2>
<p>Сравнение честное: каждая пара — <b>один и тот же артефакт того же качества</b>,
только с разной заточкой. Пары, где продаж меньше {MIN_N} за неделю, выброшены —
иначе один случайный лот перекашивает картину.</p>
{t_price}
<p>То есть на дешёвом артефакте заточка удорожает предмет
<b>×{1 + m_low / 100:.1f}</b>, а на дорогом — всего
<b>×{1 + m_high / 100:.1f}</b>. Причина простая: точат в основном то, что дешевле
не жалко, и заточенных дорогих артефактов на рынке мало, а покупателей на них
ещё меньше.</p>

<h2>То же самое по качеству</h2>
{t_qlt}
<p>Качество и цена связаны, поэтому картина повторяется: чем выше качество
базового артефакта, тем меньше в процентах добавляет заточка.</p>

<h2>Сколько добавляет каждая ступень</h2>
<p>По всей выборке, без разбивки по цене — просто чтобы видеть порядок:</p>
{ladder}

<h2>Самые дорогие заточенные позиции сейчас</h2>
<p>Обратите внимание: у этих артефактов надбавка как раз небольшая — это
верхний ценовой диапазон из таблицы выше.</p>
{top}
{snap(' — <a href="/auction">биржа артефактов</a>')}

<h2>Что из этого следует</h2>
<ul>
  <li><b>Точить на продажу выгодно на дешёвых артефактах.</b> ×{1 + m_low / 100:.1f}
    к цене — это и есть заработок на заточке. На дорогих
    (×{1 + m_high / 100:.1f}) вложенные ресурсы почти не отбиваются.</li>
  <li><b>Дорогой артефакт проще купить уже заточенным.</b> Переплата в этом
    диапазоне всего {m_high:+.0f}% — дешевле, чем самому жечь ресурсы.</li>
  <li><b>+5 — самая дешёвая ступень.</b> Медианная надбавка по всей выборке
    {med.get(5, 0):+.0f}% против {med.get(15, 0):+.0f}% у +15: первые уровни
    достаются заметно дешевле последних.</li>
  <li><b>Заточка переносится при бартере.</b> Если старое снаряжение уже на +15,
    после обмена на новое уровень заточки сохраняется — значит сначала бартер,
    потом добивать заточку, а не наоборот.</li>
</ul>

<blockquote><p><b>Коротко.</b> Заточка дешёвого артефакта поднимает цену примерно
×{1 + m_low / 100:.1f}, дорогого — всего ×{1 + m_high / 100:.1f}. Отсюда правило:
<b>дешёвое точить самому и продавать, дорогое — покупать уже заточенным</b>. Цены по
корзинам заточки — на <a href="/auction">бирже артефактов</a>, подбор артефактов
под сборку — в <a href="/builds">калькуляторе сборок</a>.</p></blockquote>
"""
    write("zatochka-artefaktov-cena", {
        "slug": "zatochka-artefaktov-cena",
        "title": "Заточка артефактов в STALZONE: сколько реально стоит +15",
        "description": ("Сколько заточка добавляет к цене артефакта в STALZONE "
                        "(Сталкрафт) — расчёт по истории продаж аукциона для +5, +10 и "
                        "+15 при одинаковом качестве. Почему дешёвое выгодно точить "
                        "самому, а дорогое дешевле купить уже заточенным."),
        "created_at": TODAY, "updated_at": TODAY,
        "cover": f"/{pairs[0]['item']['icon']}" if pairs else "",
        "tags": ["Заточка", "Артефакты", "Аукцион", "Экономика"],
    }, html)


