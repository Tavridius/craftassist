def build_barter():
    d = g("/api/barter/top")
    rows = [r for r in d["rows"]
            if r.get("trust") == "ok" and r.get("sell_fresh")
            and (r.get("cost") or 0) > 0 and (r.get("sell_net") or 0) > r["cost"]]
    for r in rows:
        r["diff"] = r["sell_net"] - r["cost"]
    rows.sort(key=lambda r: -r["diff"])
    top = rows[:10]

    def age_cell(r):
        a = r.get("sale_age_days") or 0
        return "сегодня" if a < 1 else f"{a:.0f} дн. назад"

    t = table(
        ["предмет", "где", "стоимость входов", "продажа (чистыми)", "выгода",
         "продажа была"],
        [[name_cell(r),
          f'{r["settlement_name"]} · ур.{r["level"]}',
          rub(r["cost"]), rub(r["sell_net"]),
          f'<b>+{rub(r["diff"])}</b>', age_cell(r)] for r in top])

