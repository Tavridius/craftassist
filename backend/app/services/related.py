"""Подбор связанных ссылок под текст патчноута.

Зачем: страницы патчей индексируются за сутки и собирают заметный трафик
(зеркало анонса Электрошторма дало 42 входа за двое суток — больше, чем весь
раздел /patches за предыдущий месяц), но никуда не ведут. Отказы на патчах
20-75%. Блок «Смотрите также» закрывает и это, и обход: у сайта 365 страниц
в поиске из 2387 в sitemap, внутренние ссылки на гайды тут кстати.

Подбор простой и объяснимый: ищем в тексте патча основы слов, каждая основа
привязана к разделу. Гайды матчим их же тегами и словами заголовка. Порядок
выдачи — гайды (они конверсионнее инструментов на холодном трафике), затем
инструменты, затем каталог гайдов как заглушка.
"""
import re

from app.db import guides

# основа слова -> (адрес, подпись). Основы без окончаний: «аукцион» ловит
# «аукциона/аукционе», «сборк» — «сборки/сборкам».
_TOOLS: list[tuple[tuple[str, ...], str, str]] = [
    (("аукцион", "аук ", "лот", "перекуп"), "/auction", "биржа артефактов"),
    (("бартер", "торговц", "обменя"), "/barter", "калькулятор бартера"),
    (("крафт", "рецепт", "чертёж", "чертеж"), "/craft", "калькулятор крафта"),
    (("сборк", "артефакт", "контейнер"), "/builds", "калькулятор сборок"),
    (("операци",), "/operations", "Операции"),
    (("квест", "задани", "сюжет"), "/quests", "квесты и прохождения"),
    (("промокод", "промо-код"), "/promo", "промокоды"),
    (("заточк", "точил"), "/market", "цены и обороты"),
    (("оружи", "ствол", "автомат", "винтовк", "дробовик"), "/compare", "сравнение предметов"),
    (("брон", "экзо", "костюм", "шлем"), "/items", "база предметов"),
]

_STOP = {"stalzone", "сталкрафт", "сталзон", "игре", "игры", "патч", "новый",
         "новые", "новая", "который", "которые", "можно", "будет", "теперь"}


def _norm(s: str) -> str:
    """Текст в нижнем регистре без тегов — по нему ищем основы."""
    return re.sub(r"\s+", " ", re.sub(r"<[^>]+>", " ", s or "")).lower()


def _words(s: str) -> set[str]:
    return {w for w in re.findall(r"[а-яёa-z]{4,}", _norm(s)) if w not in _STOP}


def for_patch(title: str, anons: str = "", body: str = "",
              limit: int = 5) -> list[dict]:
    """Ссылки под конкретный патч: [{"href": ..., "text": ...}].

    Тело патча берём урезанным — в нём тысячи слов, и на длинном балансном
    разделе совпадёт вообще всё. Заголовок и анонс весят больше.
    """
    head = f"{title} {anons}"
    text = _norm(head) + " " + _norm(body)[:4000]
    head_words = _words(head)

    out: list[dict] = []
    seen: set[str] = set()

    # 1. гайды: считаем пересечение слов заголовка/тегов гайда с текстом патча,
    #    совпадение в заголовке самого патча весит вдвое
    scored = []
    for g in guides.list_guides():
        gw = _words(g.get("title", "")) | {t.lower() for t in (g.get("tags") or [])}
        score = sum(2 if w in head_words else 1 for w in gw if w in text)
        if score:
            scored.append((score, g["slug"], g["title"]))
    for _, slug, gtitle in sorted(scored, reverse=True)[:2]:
        href = f"/guides/{slug}"
        if href not in seen:
            seen.add(href)
            out.append({"href": href, "text": gtitle})

    # 2. инструменты по основам слов
    for stems, href, label in _TOOLS:
        if href in seen:
            continue
        if any(st in text for st in stems):
            seen.add(href)
            out.append({"href": href, "text": label})
        if len(out) >= limit:
            break

    # 3. заглушка — чтобы блок никогда не выходил пустым
    if len(out) < 2 and "/guides" not in seen:
        out.append({"href": "/guides", "text": "все гайды по игре"})
    return out[:limit]
